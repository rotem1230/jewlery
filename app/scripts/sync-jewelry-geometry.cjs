#!/usr/bin/env node
/**
 * Embeds the backend's parametric jewelry geometry (backend/src/jewelry: catalog.ts, motifs.ts,
 * geometry.ts) in the app's 3D studio, so the preview, the STL export and the rendered pictures are
 * built by the same code, and copies the catalogue (the client's stones, colours, settings and
 * elements) for the studio's screens.
 *
 *   node scripts/sync-jewelry-geometry.cjs          writes src/lib/jewelryGeometry.generated.ts
 *                                                   and src/lib/jewelryCatalog.generated.ts
 *   node scripts/sync-jewelry-geometry.cjs --check  exits 1 when a generated file is stale
 *
 * The three sources are joined (their imports of each other removed), transpiled to ES2017 and
 * wrapped so they define `window.JewelryGeometry` inside the viewer's WebView.
 */
const { createHash } = require('crypto')
const { existsSync, readFileSync, writeFileSync } = require('fs')
const { join } = require('path')
const ts = require('typescript')

const APP = join(__dirname, '..')
const JEWELRY = join(APP, '..', 'backend', 'src', 'jewelry')
/** In dependency order. */
const SOURCES = ['catalog.ts', 'motifs.ts', 'geometry.ts']
const TARGET = join(APP, 'src', 'lib', 'jewelryGeometry.generated.ts')
const CATALOG_TARGET = join(APP, 'src', 'lib', 'jewelryCatalog.generated.ts')

// Line endings do not count: a Windows checkout may turn them into CRLF.
const lf = (text) => text.replace(/\r\n/g, '\n')

/** The sources, joined in order (what the hash covers). */
function joinedSources() {
  return SOURCES.map((file) => lf(readFileSync(join(JEWELRY, file), 'utf8'))).join('\n')
}

function generate(joined) {
  const sha = createHash('sha256').update(joined).digest('hex')
  // The files import each other; joined into one script, those imports go.
  const withoutLocalImports = joined.replace(/^import\s[\s\S]*?\sfrom\s+'\.\/[A-Za-z]+';\s*$/gm, '')
  const js = ts.transpileModule(withoutLocalImports, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2017, removeComments: true },
  }).outputText
  const wrapped = `(function () {\nvar exports = {};\n${js}\nwindow.JewelryGeometry = exports;\n})();\n`
  return [
    '/* eslint-disable */',
    '// Generated by scripts/sync-jewelry-geometry.cjs from backend/src/jewelry (catalog, motifs, geometry) — do not edit.',
    '// Run `node scripts/sync-jewelry-geometry.cjs` after changing the backend geometry.',
    '',
    `export const JEWELRY_GEOMETRY_SOURCE_SHA256 = '${sha}'`,
    '',
    `export const JEWELRY_GEOMETRY_JS = ${JSON.stringify(wrapped)}`,
    '',
  ].join('\n')
}

function generateCatalog(source) {
  return [
    '/* eslint-disable */',
    '// Generated by scripts/sync-jewelry-geometry.cjs from backend/src/jewelry/catalog.ts — do not edit.',
    '// Run `node scripts/sync-jewelry-geometry.cjs` after changing the backend catalogue.',
    '',
    source,
  ].join('\n')
}

if (!SOURCES.every((file) => existsSync(join(JEWELRY, file)))) {
  console.error(`Backend geometry not found in ${JEWELRY}`)
  process.exit(1)
}
const outputs = [
  [TARGET, generate(joinedSources())],
  [CATALOG_TARGET, generateCatalog(lf(readFileSync(join(JEWELRY, 'catalog.ts'), 'utf8')))],
]
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([file, text]) => (existsSync(file) ? lf(readFileSync(file, 'utf8')) : '') !== text)
  if (stale.length) {
    stale.forEach(([file]) => console.error(`${file} is stale: run node scripts/sync-jewelry-geometry.cjs`))
    process.exit(1)
  }
  console.log('jewelry geometry is in sync')
} else {
  outputs.forEach(([file, text]) => {
    writeFileSync(file, text)
    console.log(`wrote ${file}`)
  })
}
